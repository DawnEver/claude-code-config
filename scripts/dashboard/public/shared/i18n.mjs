/** `key` in `lang`, English when that language lacks it, the key itself when nothing has it. */
export function t(key, lang = 'en', vars = {}) {
  const e = TABLE[key];
  const v = e?.[lang] ?? e?.en;
  return v === undefined ? key : typeof v === 'function' ? v(vars) : v;
}

