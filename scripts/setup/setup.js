const isWindows = process.platform === 'win32';

export function discoverCodexSkillLinks(baseSourceDir = sourceDir) {
  const skillsDir = path.join(baseSourceDir, 'skills');
  if (!fs.existsSync(skillsDir)) return [];

  return fs.readdirSync(skillsDir, { withFileTypes: true })
    .filter(entry => {
      if (entry.name.startsWith('.')) return false;
      if (entry.isDirectory()) return true;
      if (!entry.isSymbolicLink()) return false;

      try {
        return fs.statSync(path.join(skillsDir, entry.name)).isDirectory();
      } catch {
        return false;
      }
    })
    .map(entry => ({
      src: path.join('skills', entry.name),
      dest: path.join('skills', entry.name),
      type: 'dir',
    }));
}

export function getCodexLinks(baseSourceDir = sourceDir) {
  return [...CODEX_LINKS, ...discoverCodexSkillLinks(baseSourceDir)];
}

// Legacy installs linked the whole skills dir (`~/.codex/skills -> repo/skills`).
// We now link skills individually, but if the directory is still a junction, the
// per-skill link destinations resolve *through* it back into the repo, producing
// self-referential junctions inside repo/skills. Convert the legacy link to a
// real directory first so per-skill links land in ~/.codex, not the repo.
export function ensureRealDir(dirPath) {
  const stat = fs.lstatSync(dirPath, { throwIfNoEntry: false });
  if (stat && stat.isSymbolicLink()) {
    fs.unlinkSync(dirPath);
  }
  fs.mkdirSync(dirPath, { recursive: true });
}

export function removeExisting(destPath) {
  const stat = fs.lstatSync(destPath, { throwIfNoEntry: false });
  if (!stat) return false;

  if (stat.isDirectory() && !stat.isSymbolicLink()) {
    fs.rmSync(destPath, { recursive: true, force: true });
  } else {
    fs.unlinkSync(destPath);
  }
  return true;
}

// Windows paths are case-insensitive, and the drive letter's case follows how the script was
// invoked (`node c:\...` vs `C:\...`), so an exact compare re-links links that were fine.
function samePath(a, b) {
  const x = path.resolve(a), y = path.resolve(b);
  return isWindows ? x.toLowerCase() === y.toLowerCase() : x === y;
}

function filesMatch(a, b) {
  try {
    return fs.readFileSync(a).equals(fs.readFileSync(b));
  } catch {
    return false;
  }
}

// A hard link is the fallback when a file symlink is not permitted (see createLink). It is
// indistinguishable from a plain file by lstat, so identify one by file identity instead:
// same volume (dev) and same file record (ino).
export function isHardLinked(srcPath, destPath) {
  try {
    const a = fs.statSync(srcPath);
    const b = fs.statSync(destPath);
    return a.ino !== 0 && a.ino === b.ino && a.dev === b.dev;
  } catch {
    return false;
  }
}

// Windows only grants file symlinks to holders of SeCreateSymbolicLinkPrivilege (Developer
// Mode, or an elevated shell). Directory links use junctions, which need no privilege, so
// only `type: 'file'` entries can fail this way. Hard links need no privilege either and are
// genuinely two-way like a symlink -- but only while both names keep pointing at the same
// file record: a writer that REPLACES rather than edits (OneDrive sync-down, `git checkout`,
// an atomic save) breaks the link and silently leaves a stale copy behind. Re-run setup with
// --replace to re-link when that happens; unlinked entries are reported on every run.
function createLink(srcPath, destPath, type, hardlink) {
  if (hardlink) {
    fs.linkSync(srcPath, destPath);
    return 'hardlink';
  }
  const symlinkType = isWindows ? (type === 'dir' ? 'junction' : 'file') : undefined;
  try {
    fs.symlinkSync(srcPath, destPath, symlinkType);
    return 'symlink';
  } catch (err) {
    if (!(isWindows && type === 'file' && err.code === 'EPERM')) throw err;
    fs.linkSync(srcPath, destPath);
    return 'hardlink';
  }
}

// Link destPath -> srcPath without ever destroying what is already there: an existing entry
// is moved aside first and moved back if linking throws. (Deleting up front is what cost a
// live ~/.claude/settings.json once the symlink behind it started failing.)
export function linkEntry(srcPath, destPath, link, replace) {
  if (!fs.existsSync(srcPath)) {
    return { status: 'skip', message: `source not found: ${srcPath}` };
  }

  fs.mkdirSync(path.dirname(destPath), { recursive: true });

  const stat = fs.lstatSync(destPath, { throwIfNoEntry: false });

  if (stat) {
    if (stat.isSymbolicLink()) {
      const existingTarget = fs.readlinkSync(destPath);
      const onTarget = samePath(path.resolve(path.dirname(destPath), existingTarget), srcPath);
      // A hardlink-required entry already satisfied by a symlink is converted without
      // --replace: the target is identical, so swapping link kinds loses nothing.
      if (onTarget && !link.hardlink) {
        return { status: 'ok', message: 'already linked' };
      }
      if (onTarget && link.hardlink) {
        replace = true;
      }
    } else if (link.type === 'file' && isHardLinked(srcPath, destPath)) {
      return { status: 'ok', message: 'already linked (hard link)' };
    }

    if (!replace) {
      return {
        status: 'skip',
        message: link.type === 'file' && stat.isFile()
          ? 'plain file, not linked - re-run with --replace to re-link'
          : 'already exists (remove manually to re-link, or use --replace)',
      };
    }
  }

  const notes = [];
  let backupPath = null;
  if (stat) {
    backupPath = `${destPath}.setup-bak`;
    fs.rmSync(backupPath, { recursive: true, force: true });
    fs.renameSync(destPath, backupPath);
  }

  let kind;
  try {
    kind = createLink(srcPath, destPath, link.type, link.hardlink);
  } catch (err) {
    if (backupPath) fs.renameSync(backupPath, destPath);
    throw err;
  }

  if (backupPath) {
    // An unlinked plain file may hold edits the repo never saw -- a hard link that broke
    // and drifted. Keep that one; anything matching the source is safe to drop.
    if (stat.isFile() && !stat.isSymbolicLink() && !filesMatch(srcPath, backupPath)) {
      notes.push(`replaced existing - kept unlinked copy at ${path.basename(backupPath)}`);
    } else {
      fs.rmSync(backupPath, { recursive: true, force: true });
      notes.push('removed existing');
    }
  }

  return { status: 'link', kind, notes };
}

function processLinks(links, baseDir, counters) {
  for (const link of links) {
    const srcPath = path.join(sourceDir, link.src);
    const destPath = path.join(baseDir, link.dest);

    let result;
    try {
      result = linkEntry(srcPath, destPath, link, counters.replace);
    } catch (err) {
      result = { status: 'error', message: err.message, code: err.code };
    }

    for (const note of result.notes || []) console.log(`REMV  ${link.dest} - ${note}`);

    if (result.status === 'link') {
      console.log(`LINK  ${link.dest} - ${srcPath}${result.kind === 'hardlink' ? ' (hard link)' : ''}`);
      counters.created++;
    } else if (result.status === 'ok') {
      console.log(`OK    ${link.dest} - ${result.message}`);
      counters.skipped++;
    } else if (result.status === 'skip') {
      console.log(`SKIP  ${link.dest} - ${result.message}`);
      counters.skipped++;
    } else {
      console.log(`ERR   ${link.dest} - ${result.message}`);
      if (isWindows && result.code === 'EXDEV') {
        console.log('      Hint: the hard-link fallback needs source and target on one volume');
      } else if (isWindows && result.code === 'EPERM') {
        console.log('      Hint: Enable Developer Mode in Windows Settings, or run as Administrator');
      }
      counters.errors++;
    }
  }
}

export function setup() {
  const args = process.argv.slice(2);
  const replace = args.includes('--replace') || args.includes('-r');

  console.log(`Source: ${sourceDir}`);
  console.log(`Claude target: ${claudeDir}`);
  console.log(`Codex target: ${codexDir}`);
  if (replace) console.log('Mode: replace existing files/dirs\n');
  else console.log('');

  // Ensure claude_settings.json exists (copy from template if not)
  const settingsPath = path.join(sourceDir, 'claude_settings.json');
  const settingsTemplatePath = path.join(sourceDir, 'claude_settings.template.json');
  if (!fs.existsSync(settingsPath) && fs.existsSync(settingsTemplatePath)) {
    fs.copyFileSync(settingsTemplatePath, settingsPath);
    console.log('COPY  claude_settings.template.json - claude_settings.json');
  }

  // Ensure codex_config.toml exists (copy from template if not)
  const codexConfigPath = path.join(sourceDir, 'codex_config.toml');
  const codexConfigTemplatePath = path.join(sourceDir, 'codex_config.template.toml');
  if (!fs.existsSync(codexConfigPath) && fs.existsSync(codexConfigTemplatePath)) {
    fs.copyFileSync(codexConfigTemplatePath, codexConfigPath);
    console.log('COPY  codex_config.template.toml - codex_config.toml');
  }

  // Ensure claude_env_settings.json exists (copy from template if not)
  const envSettingsPath = path.join(sourceDir, 'claude_env_settings.json');
  const envSettingsTemplatePath = path.join(sourceDir, 'claude_env_settings.template.json');
  if (!fs.existsSync(envSettingsPath) && fs.existsSync(envSettingsTemplatePath)) {
    fs.copyFileSync(envSettingsTemplatePath, envSettingsPath);
    console.log('COPY  claude_env_settings.template.json - claude_env_settings.json');
  }

  // Ensure the MACHINE-LOCAL secrets file exists (copied from a desensitized template).
  // Lives in ~/.claude — a REAL per-machine dir (only specific children are junctions into
  // the repo) — so it never syncs via OneDrive. Each machine fills in its own API keys here;
  // the shared claude_env_settings.json carries no secrets.
  const localEnvSettingsPath = path.join(claudeDir, 'claude_env_settings.local.json');
  const localEnvSettingsTemplatePath = path.join(sourceDir, 'claude_env_settings.local.template.json');
  if (!fs.existsSync(localEnvSettingsPath) && fs.existsSync(localEnvSettingsTemplatePath)) {
    fs.copyFileSync(localEnvSettingsTemplatePath, localEnvSettingsPath);
    console.log('COPY  claude_env_settings.local.template.json - ~/.claude/claude_env_settings.local.json');
  }

  // One-time local-file migration: pre-2026-08-25 local files held
  // `env:<provider>: { ANTHROPIC_API_KEY: "sk-..." }` blocks. The new shape is
  // `providers: { <provider>: { apiKey: "..." } }` (see docs/providers.md).
  // setup.js auto-migrates on first run after the refactor — backup is written
  // to `claude_env_settings.local.json.setup-bak` (same convention as linkEntry).
  const migration = migrateLocalEnvSettings({ localPath: localEnvSettingsPath });
  if (migration.status === 'migrated') {
    console.log(`MIGR  claude_env_settings.local.json — ${migration.providers.length} provider(s) converted to providers.<name>.apiKey (backup: ${path.basename(migration.backupPath)})`);
  } else if (migration.status === 'malformed') {
    console.log(`NOTE  could not migrate local file (malformed JSON): ${migration.error}`);
  } else if (migration.status === 'mixed') {
    const legacy = migration.legacyKeys.map(k => k.replace(/^env:/, '')).join(', ');
    const news = migration.newKeys.join(', ');
    console.log(`NOTE  local file is in mixed shape (both env: and providers: present); left untouched.`);
    console.log(`      legacy env: keys still present: ${legacy}`);
    console.log(`      already in providers.*:         ${news}`);
    console.log(`      Move the apiKey from each env:<x> into providers.<x>.apiKey, then delete the env:<x> block.`);
    console.log(`      See docs/providers.md § Migrating from the legacy env:<provider> shape.`);
  }

  const counters = { created: 0, skipped: 0, errors: 0, replace };

  // Regenerate the derivable codex artifacts from the shared providers registry:
  // the [model_providers.*] section of codex_config.toml (only when that file
  // exists) AND the gitignored repo models.json (unconditionally — models.json
  // derives purely from providers.<name>.models and is unrelated to
  // codex_config.toml). Without this, `cods` / `cogmi` fail with "model provider
  // not found" on fresh installs. The generated section lives between two
  // setup-managed markers; user edits above the markers are preserved verbatim.
  // See scripts/setup/inject-codex-providers.mjs.
  //
  // This runs BEFORE link creation on purpose: models.json is gitignored, so on a
  // fresh clone the repo file does not exist when links are processed. Generating
  // it first lets the `~/.codex/models.json` link be created in the same run.
  const artifacts = regenerateCodexArtifacts({
    settingsPath: envSettingsPath,
    codexConfigPath,
    modelsPath: path.join(sourceDir, 'models.json'),
  });

  if (artifacts.settings === 'unparseable' || artifacts.settings === 'missing') {
    console.log(`ERR   claude_env_settings.json - ${artifacts.settings === 'unparseable'
      ? `could not parse JSON: ${artifacts.error.message}`
      : 'not found; skipping codex artifact generation'}`);
    counters.errors++;
  } else {
    if (artifacts.providers.status === 'updated') {
      console.log(`INJECT codex_config.toml — ${artifacts.providers.providers} [model_providers.*] block(s) generated from providers.<name>`);
    } else if (artifacts.providers.status === 'empty') {
      console.log('NOTE   codex_config.toml — no provider has a codex-side declaration; nothing to inject');
    } else if (artifacts.providers.status === 'no-config') {
      console.log('NOTE   codex_config.toml — not present; skipped [model_providers.*] injection (models.json still generated)');
    }
    if (artifacts.models.status === 'updated') {
      console.log(`INJECT models.json — ${artifacts.models.models} model catalog entr(y/ies) generated from providers.<name>.models`);
    } else if (artifacts.models.status === 'empty') {
      console.log('NOTE   models.json — no provider declares a codex model; nothing to inject');
    }
  }

  console.log('--- Claude ---');
  processLinks(CLAUDE_LINKS, claudeDir, counters);

  console.log('\n--- Codex ---');
  // Convert any legacy `~/.codex/skills` junction into a real directory before
  // creating per-skill links (otherwise they self-reference into the repo).
  ensureRealDir(path.join(codexDir, 'skills'));
  processLinks(getCodexLinks(), codexDir, counters);

  // Clone or update cc-market (community plugin marketplace)
  console.log('\n--- Plugins (cc-market) ---');
  const ccMarketDir = path.join(sourceDir, 'cc-market');
  if (fs.existsSync(path.join(ccMarketDir, '.git'))) {
    try {
      execFileSync('git', ['pull', '--ff-only'], { cwd: ccMarketDir, stdio: 'pipe' });
      console.log('OK    cc-market - pulled latest');
    } catch {
      console.log('OK    cc-market - already exists (could not pull)');
    }
  } else if (fs.existsSync(ccMarketDir)) {
    console.log('SKIP  cc-market - directory exists but is not a git repo');
  } else {
    try {
      execFileSync('git', ['clone', 'https://github.com/DawnEver/cc-market'], { cwd: sourceDir, stdio: 'pipe' });
      console.log('OK    cc-market - cloned from https://github.com/DawnEver/cc-market');
    } catch (err) {
      console.log(`ERR   cc-market - ${err.stderr?.toString().trim() || err.message}`);
      counters.errors++;
    }
  }
  // Note: plugin enablement + the cc-market marketplace live in claude_settings.template.json,
  // which setup copies to claude_settings.json on a fresh install. Existing-install deltas
  // (enabling a new plugin, retiring a merged one) are migrate's job — see
  // skills/migrate/migrate.js `migrateRetiredPlugins()`. setup does not mutate enabledPlugins.

  // Fix LSP commands on Windows (.cmd extension required)
  fixLspWindows();

  // Check macOS notification helper
  if (process.platform === 'darwin') {
    console.log('\n--- macOS Notifications ---');
    if (!checkMacNotify()) counters.errors++;
  }

  // Install shell aliases
  console.log('\n--- Shell Aliases ---');
  installShellAliases(claudeDir, sourceDir);

  console.log(`\nDone: ${counters.created} linked, ${counters.skipped} skipped, ${counters.errors} errors`);
}

if (path.resolve(process.argv[1] || '') === path.resolve(__dirname, 'setup.js')) {
  setup();
}
